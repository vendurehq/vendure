import type { Tree } from '@nx/devkit';
import { createTreeWithEmptyWorkspace } from '@nx/devkit/testing';
import { beforeEach, describe, expect, it } from 'vitest';

import syncTsconfigGenerator from './generator';

const HEADER = '// Generated from the package schema by `nx sync`. Do not edit this file by hand.\n';

let tree: Tree;

function addPackage(root: string, files: Record<string, string>) {
    for (const [path, content] of Object.entries(files)) {
        tree.write(`${root}/${path}`, content);
    }
}

function readJsonc(path: string) {
    const content = tree.read(path, 'utf-8') ?? '';
    expect(content.startsWith(HEADER)).toBe(true);
    return JSON.parse(content.slice(HEADER.length));
}

beforeEach(() => {
    tree = createTreeWithEmptyWorkspace();
    tree.write('package.json', JSON.stringify({ name: 'workspace', workspaces: ['packages/*'] }));
    tree.write(
        'tsconfig.json',
        JSON.stringify({ compilerOptions: { lib: ['es2019', 'esnext.asynciterable'] } }),
    );
});

describe('syncTsconfigGenerator', () => {
    it('writes the tsconfig files of a package with src/index.ts', async () => {
        addPackage('packages/foo-plugin', {
            'package.json': JSON.stringify({
                name: '@vendure/foo-plugin',
                main: 'dist/index.js',
                exports: { '.': './dist/index.js', './preload': { default: './dist/preload.js' } },
            }),
            'src/index.ts': '',
            'src/preload.ts': '',
            'src/foo.plugin.ts': '',
            'src/sub/index.ts': '',
        });

        const result = await syncTsconfigGenerator(tree);

        expect(result.outOfSyncMessage).toContain('packages/foo-plugin/tsconfig.json');
        expect(readJsonc('packages/foo-plugin/tsconfig.json')).toEqual({
            extends: '../../tsconfig.json',
            compilerOptions: { declaration: true, removeComments: false, sourceMap: true },
        });
        expect(readJsonc('packages/foo-plugin/tsconfig.build.json')).toEqual({
            extends: './tsconfig.json',
            compilerOptions: { outDir: './dist', rootDir: './src' },
            files: ['./src/index.ts', './src/preload.ts', './src/sub/index.ts'],
        });
        expect(tree.exists('packages/foo-plugin/tsconfig.spec-d.json')).toBe(false);
    });

    it('compiles from the package root when the entry point is index.ts', async () => {
        addPackage('packages/foo-plugin', {
            'package.json': JSON.stringify({ name: '@vendure/foo-plugin', main: 'lib/index.js' }),
            'index.ts': '',
            'src/plugin.ts': '',
        });

        await syncTsconfigGenerator(tree);

        expect(readJsonc('packages/foo-plugin/tsconfig.build.json')).toEqual({
            extends: './tsconfig.json',
            compilerOptions: { outDir: './lib', rootDir: '.' },
            files: ['./index.ts'],
        });
    });

    it('adds JSX and DOM types when src has tsx files outside src/dashboard', async () => {
        addPackage('packages/foo-plugin', {
            'package.json': JSON.stringify({ name: '@vendure/foo-plugin' }),
            'src/index.ts': '',
            'src/plugin.ts': '',
            'src/ui/app.tsx': '',
        });

        await syncTsconfigGenerator(tree);

        expect(readJsonc('packages/foo-plugin/tsconfig.json').compilerOptions).toEqual({
            declaration: true,
            removeComments: false,
            sourceMap: true,
            jsx: 'react-jsx',
            lib: ['es2019', 'esnext.asynciterable', 'dom'],
        });
    });

    it('follows a change to the lib of the root tsconfig', async () => {
        addPackage('packages/foo-plugin', {
            'package.json': JSON.stringify({ name: '@vendure/foo-plugin' }),
            'src/index.ts': '',
            'src/plugin.ts': '',
            'src/ui/app.tsx': '',
        });
        await syncTsconfigGenerator(tree);

        tree.write('tsconfig.json', JSON.stringify({ compilerOptions: { lib: ['es2022'] } }));
        const result = await syncTsconfigGenerator(tree);

        expect(result.outOfSyncMessage).toContain('packages/foo-plugin/tsconfig.json');
        expect(readJsonc('packages/foo-plugin/tsconfig.json').compilerOptions.lib).toEqual(['es2022', 'dom']);
    });

    it('does not add JSX for a dashboard extension', async () => {
        addPackage('packages/foo-plugin', {
            'package.json': JSON.stringify({ name: '@vendure/foo-plugin' }),
            'src/index.ts': '',
            'src/plugin.ts': '',
            'src/dashboard/index.tsx': '',
        });

        await syncTsconfigGenerator(tree);

        expect(readJsonc('packages/foo-plugin/tsconfig.json').compilerOptions.jsx).toBeUndefined();
    });

    it('excludes src/dashboard when it has its own tsconfig', async () => {
        addPackage('packages/foo-plugin', {
            'package.json': JSON.stringify({ name: '@vendure/foo-plugin' }),
            'src/index.ts': '',
            'src/plugin.ts': '',
            'src/dashboard/index.tsx': '',
            'src/dashboard/tsconfig.json': '{}',
        });

        await syncTsconfigGenerator(tree);

        expect(readJsonc('packages/foo-plugin/tsconfig.json').exclude).toEqual(['src/dashboard']);
    });

    it('does not exclude src/dashboard when it has no tsconfig', async () => {
        addPackage('packages/foo-plugin', {
            'package.json': JSON.stringify({ name: '@vendure/foo-plugin' }),
            'src/index.ts': '',
            'src/plugin.ts': '',
            'src/dashboard/index.tsx': '',
        });

        await syncTsconfigGenerator(tree);

        expect(readJsonc('packages/foo-plugin/tsconfig.json').exclude).toBeUndefined();
    });

    it('writes tsconfig.spec-d.json only while there are type-level tests', async () => {
        addPackage('packages/foo-plugin', {
            'package.json': JSON.stringify({ name: '@vendure/foo-plugin' }),
            'src/index.ts': '',
            'src/plugin.ts': '',
            'src/foo.spec-d.ts': '',
        });

        await syncTsconfigGenerator(tree);
        expect(readJsonc('packages/foo-plugin/tsconfig.spec-d.json')).toEqual({
            extends: './tsconfig.json',
            compilerOptions: { noEmit: true },
            include: ['src/**/*.spec-d.ts'],
        });

        tree.delete('packages/foo-plugin/src/foo.spec-d.ts');
        const result = await syncTsconfigGenerator(tree);
        expect(result.outOfSyncMessage).toContain('packages/foo-plugin/tsconfig.spec-d.json');
        expect(tree.exists('packages/foo-plugin/tsconfig.spec-d.json')).toBe(false);
    });

    it('reports nothing when the files are up to date, and overwrites a manual change', async () => {
        addPackage('packages/foo-plugin', {
            'package.json': JSON.stringify({ name: '@vendure/foo-plugin' }),
            'src/index.ts': '',
            'src/plugin.ts': '',
        });
        await syncTsconfigGenerator(tree);
        const generated = tree.read('packages/foo-plugin/tsconfig.json', 'utf-8');

        expect(await syncTsconfigGenerator(tree)).toEqual({});

        tree.write('packages/foo-plugin/tsconfig.json', '{ "compilerOptions": { "strict": false } }');
        const result = await syncTsconfigGenerator(tree);
        expect(result.outOfSyncMessage).toBe(
            'These tsconfig files do not match the package schema:\npackages/foo-plugin/tsconfig.json',
        );
        expect(tree.read('packages/foo-plugin/tsconfig.json', 'utf-8')).toBe(generated);
    });

    it('does not touch packages that are not Vendure plugins', async () => {
        addPackage('packages/core', {
            'package.json': JSON.stringify({ name: '@vendure/core' }),
            'src/index.ts': '',
            'tsconfig.json': '{}',
        });

        expect(await syncTsconfigGenerator(tree)).toEqual({});
        expect(tree.read('packages/core/tsconfig.json', 'utf-8')).toBe('{}');
    });
});
