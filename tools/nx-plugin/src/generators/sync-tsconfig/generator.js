// @ts-check
const { getProjects, readJson } = require('@nx/devkit');
const { posix } = require('node:path');

const { isPluginPackage, readPluginPackage } = require('../../package-schema');

/**
 * @typedef {import('@nx/devkit').Tree} Tree
 * @typedef {import('../../package-schema').PluginPackage} PluginPackage
 * @typedef {import('../../package-schema').WorkspaceReader} WorkspaceReader
 */

const HEADER = '// Generated from the package schema by `nx sync`. Do not edit this file by hand.\n';
const TYPE_TEST_CONFIG = 'tsconfig.spec-d.json';
/** The `lib` of the root tsconfig. Packages with JSX add `dom` to it. */
const readRootLib = (/** @type {Tree} */ tree) => readJson(tree, 'tsconfig.json').compilerOptions.lib;

/**
 * Writes the `tsconfig*.json` files of every Vendure plugin package.
 * `nx sync` runs it, and `nx sync:check` fails when a file is out of date.
 *
 * @param {Tree} tree
 * @returns {Promise<{ outOfSyncMessage?: string }>}
 */
async function syncTsconfigGenerator(tree) {
    const reader = createTreeReader(tree);
    const rootLib = readRootLib(tree);
    /** @type {string[]} */
    const changed = [];
    for (const { root } of getProjects(tree).values()) {
        if (!isPluginPackage(root, reader)) {
            continue;
        }
        const pkg = readPluginPackage(root, reader);
        for (const [fileName, content] of Object.entries(await getTsconfigFiles(pkg, rootLib))) {
            const path = posix.join(root, fileName);
            if (content === undefined) {
                if (tree.exists(path)) {
                    tree.delete(path);
                    changed.push(path);
                }
            } else if (tree.read(path, 'utf-8') !== content) {
                tree.write(path, content);
                changed.push(path);
            }
        }
    }
    if (changed.length === 0) {
        return {};
    }
    return {
        outOfSyncMessage: `These tsconfig files do not match the package schema:\n${changed.join('\n')}`,
    };
}

/**
 * Returns the content of each tsconfig file of the package.
 * `undefined` means that the file must not exist.
 *
 * @param {PluginPackage} pkg
 * @param {string[]} rootLib the `lib` of the root tsconfig
 * @returns {Promise<Record<string, string | undefined>>}
 */
async function getTsconfigFiles(pkg, rootLib) {
    const toWorkspaceRoot = posix.relative(pkg.root, '.') || '.';
    /** @type {Record<string, unknown>} */
    const compilerOptions = {
        declaration: true,
        removeComments: false,
        sourceMap: true,
    };
    if (pkg.hasJsx) {
        compilerOptions.jsx = 'react-jsx';
        // `lib` replaces the list of the root tsconfig, so it repeats that list.
        compilerOptions.lib = [...rootLib, 'dom'];
    }
    return {
        'tsconfig.json': await format({
            extends: `${toWorkspaceRoot}/tsconfig.json`,
            compilerOptions,
            // A dashboard extension has its own tsconfig with the JSX, DOM and path settings it needs.
            ...(pkg.hasDashboardConfig ? { exclude: ['src/dashboard'] } : {}),
        }),
        'tsconfig.build.json': await format({
            extends: './tsconfig.json',
            compilerOptions: {
                outDir: `./${pkg.outDir}`,
                rootDir: pkg.rootDir === '.' ? '.' : './src',
            },
            files: pkg.entryFiles.map(file => `./${file}`),
        }),
        // Only the `*.spec-d.ts` files and their imports, so that `vitest --typecheck` does not
        // type-check the runtime specs. For example, the runtime spec of the email plugin reads
        // the private `EmailPlugin.options`.
        [TYPE_TEST_CONFIG]: pkg.hasTypeTests
            ? await format({
                  extends: './tsconfig.json',
                  compilerOptions: { noEmit: true },
                  include: ['src/**/*.spec-d.ts'],
              })
            : undefined,
    };
}

/**
 * Formats with the Prettier config of the repository, so that running Prettier
 * on a generated file does not make it out of date.
 *
 * @param {unknown} json
 * @returns {Promise<string>}
 */
async function format(json) {
    const prettier = await import('prettier');
    const filepath = 'tsconfig.json';
    const config = (await prettier.resolveConfig(filepath)) ?? {};
    return prettier.format(HEADER + JSON.stringify(json, null, 4), { ...config, plugins: [], filepath });
}

/**
 * @param {Tree} tree
 * @returns {WorkspaceReader}
 */
function createTreeReader(tree) {
    return {
        exists: path => tree.exists(path),
        isFile: path => tree.isFile(path),
        read: path => tree.read(path, 'utf-8') ?? '',
        children: path => tree.children(path),
    };
}

module.exports = syncTsconfigGenerator;
module.exports.default = syncTsconfigGenerator;
module.exports.getTsconfigFiles = getTsconfigFiles;
module.exports.readRootLib = readRootLib;
