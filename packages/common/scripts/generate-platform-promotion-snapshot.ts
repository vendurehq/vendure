import fs from 'node:fs';
import path from 'node:path';

import { isDashboardPromotionV1 } from '../src/platform-promotion';

/**
 * Writes the Platform catalog snapshot (src/platform-promotion-snapshot.ts). The Dashboard
 * build uses it when it cannot fetch the catalog. The Core startup banner also uses it.
 * The Core release runs this script.
 *
 * Usage: bun scripts/generate-platform-promotion-snapshot.ts [source]
 *
 * `source` is a catalog URL or a path to a JSON file with the catalog response.
 * The default is the production catalog.
 *
 * It never exits with an error. If it cannot read a valid catalog, or if
 * VENDURE_DASHBOARD_SKIP_PLATFORM_CATALOG_FETCH is `true`, it keeps the committed
 * snapshot and prints a warning.
 */

export const SNAPSHOT_FILE = path.join(__dirname, '../src/platform-promotion-snapshot.ts');
const DEFAULT_SOURCE = 'https://api.vendure.io/v1/catalog';
const SKIP_ENV = 'VENDURE_DASHBOARD_SKIP_PLATFORM_CATALOG_FETCH';

async function readCatalog(source: string): Promise<unknown> {
    if (/^https?:\/\//.test(source)) {
        const response = await fetch(source, { signal: AbortSignal.timeout(30_000) });
        if (!response.ok) {
            throw new Error(`GET ${source} returned HTTP ${response.status}`);
        }
        return response.json();
    }
    return JSON.parse(fs.readFileSync(source, 'utf-8'));
}

/**
 * Writes the snapshot from `source` to `outputFile`. Returns `false` and keeps
 * `outputFile` unchanged if `source` has no valid `dashboardPromotion` v1.
 */
export async function generatePlatformPromotionSnapshot(
    source: string,
    outputFile = SNAPSHOT_FILE,
): Promise<boolean> {
    if (process.env[SKIP_ENV] === 'true') {
        console.warn(`Platform catalog snapshot not changed: ${SKIP_ENV} is set.`);
        return false;
    }
    try {
        const catalog = (await readCatalog(source)) as { dashboardPromotion?: unknown } | null;
        const dashboardPromotion = catalog?.dashboardPromotion;
        if (!isDashboardPromotionV1(dashboardPromotion)) {
            throw new Error(`${source} has no valid dashboardPromotion with version 1`);
        }
        const output = [
            '// This file is generated by scripts/generate-platform-promotion-snapshot.ts. Do not edit it manually.',
            "import { DashboardPromotionV1 } from './platform-promotion';",
            '',
            `export const platformPromotionSnapshot: DashboardPromotionV1 = ${JSON.stringify(dashboardPromotion)};`,
            '',
        ].join('\n');
        const prettier = await import('prettier');
        const prettierOptions = await prettier.resolveConfig(outputFile);
        fs.writeFileSync(
            outputFile,
            await prettier.format(output, { ...prettierOptions, filepath: outputFile }),
        );
        console.log(`Platform catalog snapshot updated from ${source}`);
        return true;
    } catch (e: unknown) {
        console.warn(`Platform catalog snapshot not changed: ${e instanceof Error ? e.message : String(e)}`);
        return false;
    }
}

if ((import.meta as { main?: boolean }).main) {
    await generatePlatformPromotionSnapshot(process.argv[2] ?? DEFAULT_SOURCE);
}
